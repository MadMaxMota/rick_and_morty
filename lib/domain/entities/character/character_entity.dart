class CharacterEntity {
  final int id;
  final String name;
  final String image;
  final String status;
  final String species;
  final String type;
  final String gender;
  final String location;
  final String origin;
  final String episode;

  CharacterEntity({
    required this.id,
    required this.name,
    required this.image,
    required this.status,
    required this.species,
    required this.type,
    required this.gender,
    required this.location,
    required this.origin,
    required this.episode,
  });
}
